-- Professor autonomo: quem da aula por conta propria cria a propria conta e vira uma
-- "escola de uma pessoa so" (instituicao do tipo AUTONOMO). A conta so ativa apos confirmar o e-mail.

ALTER TABLE instituicao ADD COLUMN tipo VARCHAR(20) DEFAULT 'ESCOLA' NOT NULL;
ALTER TABLE instituicao ADD CONSTRAINT ck_instituicao_tipo CHECK (tipo IN ('ESCOLA', 'AUTONOMO'));

-- Contas existentes (criadas por convite ou pelo SUPER_ADMIN) ja estao ativas
ALTER TABLE usuario ADD COLUMN ativo BOOLEAN DEFAULT TRUE NOT NULL;

ALTER TABLE usuario DROP CONSTRAINT ck_usuario_papel;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_papel
    CHECK (papel IN ('SUPER_ADMIN', 'ADMIN_ESCOLA', 'PROFESSOR', 'PROFESSOR_AUTONOMO', 'ALUNO'));

-- Link de confirmacao de e-mail: como nos convites, guarda so o hash (SHA-256) do codigo
CREATE TABLE confirmacao_email (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuario (id),
    codigo_hash VARCHAR(64) NOT NULL,
    criado_em   TIMESTAMP   NOT NULL,
    expira_em   TIMESTAMP   NOT NULL,
    usado_em    TIMESTAMP,
    CONSTRAINT uk_confirmacao_email_codigo UNIQUE (codigo_hash)
);

CREATE INDEX idx_confirmacao_email_usuario ON confirmacao_email (usuario_id);
