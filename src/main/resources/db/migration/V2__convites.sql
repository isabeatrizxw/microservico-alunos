-- Convites: o ADMIN_ESCOLA convida professores e alunos; a pessoa cria a propria senha ao aceitar.
-- Guarda so o hash (SHA-256) do codigo, nunca o codigo em si.

CREATE TABLE convite (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_hash    VARCHAR(64)  NOT NULL,
    email          VARCHAR(254) NOT NULL,
    papel          VARCHAR(20)  NOT NULL,
    instituicao_id BIGINT       NOT NULL REFERENCES instituicao (id),
    turma_id       BIGINT REFERENCES turma (id),
    criado_por_id  BIGINT       NOT NULL REFERENCES usuario (id),
    criado_em      TIMESTAMP    NOT NULL,
    expira_em      TIMESTAMP    NOT NULL,
    usado_em       TIMESTAMP,
    revogado_em    TIMESTAMP,
    CONSTRAINT uk_convite_codigo UNIQUE (codigo_hash),
    CONSTRAINT ck_convite_papel CHECK (papel IN ('PROFESSOR', 'ALUNO')),
    -- Aluno entra sempre numa turma; professor nao
    CONSTRAINT ck_convite_turma CHECK (
        (papel = 'ALUNO' AND turma_id IS NOT NULL)
        OR (papel <> 'ALUNO' AND turma_id IS NULL)
    )
);

CREATE INDEX idx_convite_instituicao ON convite (instituicao_id);
CREATE INDEX idx_convite_email ON convite (email);
