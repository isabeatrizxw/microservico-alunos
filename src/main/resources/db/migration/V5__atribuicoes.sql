-- Atribuicao de aulas: qual professor da qual disciplina em qual turma.
-- O professor de escola so ve e lanca notas nas turmas/disciplinas atribuidas a ele.

CREATE TABLE atribuicao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instituicao_id BIGINT NOT NULL REFERENCES instituicao (id),
    professor_id   BIGINT NOT NULL REFERENCES usuario (id),
    turma_id       BIGINT NOT NULL REFERENCES turma (id),
    disciplina_id  BIGINT NOT NULL REFERENCES disciplina (id),
    CONSTRAINT uk_atribuicao UNIQUE (professor_id, turma_id, disciplina_id)
);

CREATE INDEX idx_atribuicao_instituicao ON atribuicao (instituicao_id);
CREATE INDEX idx_atribuicao_turma ON atribuicao (turma_id);
CREATE INDEX idx_atribuicao_disciplina ON atribuicao (disciplina_id);
