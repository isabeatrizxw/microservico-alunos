-- Link de "esqueci minha senha": como na confirmacao de e-mail, guarda so o hash (SHA-256) do codigo.

CREATE TABLE redefinicao_senha (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuario (id),
    codigo_hash VARCHAR(64) NOT NULL,
    criado_em   TIMESTAMP   NOT NULL,
    expira_em   TIMESTAMP   NOT NULL,
    usado_em    TIMESTAMP,
    CONSTRAINT uk_redefinicao_senha_codigo UNIQUE (codigo_hash)
);

CREATE INDEX idx_redefinicao_senha_usuario ON redefinicao_senha (usuario_id);
