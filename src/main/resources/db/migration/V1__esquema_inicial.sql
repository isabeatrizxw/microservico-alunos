-- Esquema inicial: instituicoes (escolas), turmas e usuarios.
-- Escrito para rodar igual no PostgreSQL (producao) e no H2 em modo PostgreSQL (dev/testes).

CREATE TABLE instituicao (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(150) NOT NULL,
    criado_em TIMESTAMP    NOT NULL
);

CREATE TABLE turma (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    instituicao_id BIGINT       NOT NULL REFERENCES instituicao (id),
    CONSTRAINT uk_turma_nome_por_instituicao UNIQUE (instituicao_id, nome)
);

CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(254) NOT NULL,
    senha_hash     VARCHAR(100) NOT NULL,
    papel          VARCHAR(20)  NOT NULL,
    instituicao_id BIGINT REFERENCES instituicao (id),
    turma_id       BIGINT REFERENCES turma (id),
    criado_em      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_papel CHECK (papel IN ('SUPER_ADMIN', 'ADMIN_ESCOLA', 'PROFESSOR', 'ALUNO')),
    -- SUPER_ADMIN (dono do sistema) nao pertence a escola nenhuma; todos os outros pertencem a uma
    CONSTRAINT ck_usuario_instituicao CHECK (
        (papel = 'SUPER_ADMIN' AND instituicao_id IS NULL)
        OR (papel <> 'SUPER_ADMIN' AND instituicao_id IS NOT NULL)
    ),
    -- So aluno fica vinculado a uma turma
    CONSTRAINT ck_usuario_turma CHECK (turma_id IS NULL OR papel = 'ALUNO')
);

CREATE INDEX idx_turma_instituicao ON turma (instituicao_id);
CREATE INDEX idx_usuario_instituicao ON usuario (instituicao_id);
CREATE INDEX idx_usuario_turma ON usuario (turma_id);
