-- Disciplinas de cada escola e notas lancadas pelos professores.
-- A nota guarda a instituicao para que toda consulta filtre pela escola de quem esta logado.

CREATE TABLE disciplina (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    instituicao_id BIGINT       NOT NULL REFERENCES instituicao (id),
    CONSTRAINT uk_disciplina_nome_por_instituicao UNIQUE (instituicao_id, nome)
);

CREATE TABLE nota (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instituicao_id BIGINT       NOT NULL REFERENCES instituicao (id),
    aluno_id       BIGINT       NOT NULL REFERENCES usuario (id),
    disciplina_id  BIGINT       NOT NULL REFERENCES disciplina (id),
    descricao      VARCHAR(100) NOT NULL,
    valor          NUMERIC(4, 2) NOT NULL,
    lancada_por_id BIGINT       NOT NULL REFERENCES usuario (id),
    lancada_em     TIMESTAMP    NOT NULL,
    atualizada_em  TIMESTAMP,
    CONSTRAINT ck_nota_valor CHECK (valor >= 0 AND valor <= 10)
);

CREATE INDEX idx_disciplina_instituicao ON disciplina (instituicao_id);
CREATE INDEX idx_nota_instituicao ON nota (instituicao_id);
CREATE INDEX idx_nota_aluno ON nota (aluno_id);
CREATE INDEX idx_nota_disciplina ON nota (disciplina_id);
